package app.enotone.playback

/**
 * Режим кэша фиксируется один раз — при сборке очереди.
 *
 * Раньше `cacheEnabledForQueue` выставлялся по запросу пользователя
 * (`useTemporaryCache`), а не по фактической готовности кэша. Если очередь
 * собрана до готовности `TransientMediaCache`, флаг оставался `true`, и
 * `prefetchCurrent`/`prefetchNext` срабатывали позже, когда кэш появлялся.
 * Плеер этой очереди кэш не читал (источник был выбран при сборке), поэтому
 * предзагрузка скачивала трек повторно — то есть дефект был в двойной загрузке,
 * а не в бездействии.
 *
 * Кэш — ускоритель, а не условие воспроизведения (ADR-0094), поэтому решение
 * принимается один раз и дальше не пересматривается до следующей сборки очереди.
 *
 * Чистая функция: без Player, диска и сети.
 */
object CacheModeDecision {
    /**
     * @param requested пользовательский режим (настройка кэша)
     * @param cacheAvailable кэш фактически готов на момент сборки очереди
     */
    fun cacheEnabledForQueue(requested: Boolean, cacheAvailable: Boolean): Boolean =
        requested && cacheAvailable
}
